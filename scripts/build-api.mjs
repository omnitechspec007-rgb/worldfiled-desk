// Builds the Vercel serverless function from the existing Netlify-format sources (netlify/functions/*.mts).
// Vercel's Hobby plan allows at most 12 functions per deployment, so ALL handlers are bundled into ONE function,
// api/[name].js, that routes by the last path segment (/api/<name> and /.netlify/functions/<name>).
// The app code is not duplicated: each route is the SAME handler. Run:  npm run build:api   (the test suite checks it is up to date).
import { build } from "esbuild";
import { readdirSync, writeFileSync, mkdirSync, rmSync, existsSync } from "node:fs";
import { resolve, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(import.meta.url), "../..");
const fnDir = resolve(root, "netlify/functions");
export const names = readdirSync(fnDir).filter((f) => f.endsWith(".mts")).map((f) => basename(f, ".mts")).sort();
export const ROUTER_FILE = "api/[name].js";

const entry = () => {
  const imports = names.map((n, i) => `import h${i} from ${JSON.stringify(resolve(fnDir, n + ".mts"))};`).join("\n");
  const table = names.map((n, i) => `  ${JSON.stringify(n)}: h${i},`).join("\n");
  return `${imports}
const HANDLERS = {
${table}
};
function route(req) {
  const parts = new URL(req.url).pathname.split("/").filter(Boolean);
  const name = parts[parts.length - 1] ?? "";
  const h = Object.prototype.hasOwnProperty.call(HANDLERS, name) ? HANDLERS[name] : null;
  if (!h) return new Response(JSON.stringify({ error: "Unknown function." }), { status: 404, headers: { "content-type": "application/json" } });
  return h(req);
}
export default { fetch: route };
`;
};

export async function bundleRouter() {
  const r = await build({
    stdin: { contents: entry(), resolveDir: root, loader: "ts", sourcefile: "api-router.ts" },
    bundle: true, platform: "node", format: "esm", target: "node20", write: false, legalComments: "none", logLevel: "silent",
    banner: { js: `// GENERATED by scripts/build-api.mjs from netlify/functions/*.mts. Do not edit by hand.\n// One function serves every route (Vercel Hobby allows at most 12 functions).\nimport { createRequire as __cr } from "node:module";\nconst require = __cr(import.meta.url);` },
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  mkdirSync(resolve(root, "api"), { recursive: true });
  for (const f of readdirSync(resolve(root, "api"))) if (f.endsWith(".js") && f !== basename(ROUTER_FILE)) rmSync(resolve(root, "api", f));
  writeFileSync(resolve(root, ROUTER_FILE), await bundleRouter());
  console.log(ROUTER_FILE + " (" + names.length + " routes: " + names.join(", ") + ")");
}
