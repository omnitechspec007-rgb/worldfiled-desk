// Builds Vercel serverless functions (api/*.js) from the existing Netlify-format sources (netlify/functions/*.mts).
// The app code is not duplicated: each api file is the SAME handler, bundled with its imports into plain JavaScript,
// so Vercel needs no TypeScript resolution. Run:  npm run build:api   (the test suite checks the files are up to date).
import { build } from "esbuild";
import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(import.meta.url), "../..");
const fnDir = resolve(root, "netlify/functions");
export const names = readdirSync(fnDir).filter((f) => f.endsWith(".mts")).map((f) => basename(f, ".mts")).sort();

export async function bundle(name) {
  const r = await build({
    stdin: { contents: `import h from ${JSON.stringify(resolve(fnDir, name + ".mts"))};\nexport default { fetch: h };\n`, resolveDir: root, loader: "ts", sourcefile: `api-${name}.ts` },
    bundle: true, platform: "node", format: "esm", target: "node20", write: false, legalComments: "none", logLevel: "silent",
    banner: { js: `// GENERATED by scripts/build-api.mjs from netlify/functions/${name}.mts. Do not edit by hand.\nimport { createRequire as __cr } from "node:module";\nconst require = __cr(import.meta.url);` },
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  mkdirSync(resolve(root, "api"), { recursive: true });
  for (const n of names) { writeFileSync(resolve(root, "api", n + ".js"), await bundle(n)); console.log("api/" + n + ".js"); }
}
